from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class LanguageTurn:
    speaker: str
    text: str


@dataclass(frozen=True, slots=True)
class LanguageScene:
    name: str
    skills: tuple[str, ...]
    turns: tuple[LanguageTurn, ...]


def _turns(*items: tuple[str, str]) -> tuple[LanguageTurn, ...]:
    return tuple(LanguageTurn(speaker, text) for speaker, text in items)


