"""Operational drills for Russian grammar, lexical relations and contextual meaning."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class GrammarTurn:
    speaker: str
    text: str


@dataclass(frozen=True, slots=True)
class GrammarScene:
    name: str
    skills: tuple[str, ...]
    turns: tuple[GrammarTurn, ...]


def _scene(name: str, skills: tuple[str, ...], *pairs: tuple[str, str]) -> GrammarScene:
    turns = tuple(GrammarTurn(speaker, text) for pair in pairs for speaker, text in (("human", pair[0]), ("bot", pair[1])))
    return GrammarScene(name, skills, turns)


